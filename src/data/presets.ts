function cloneTracks(tracks: StudioTrack[]): StudioTrack[] {
  return tracks.map((t) => ({...t, notes: t.notes.map((n) => ({...n}))}));
}

function buildSangatiSection(
  baseTracks: StudioTrack[],
  id: string,
  name: string,
  roleLabel: string,
  octaveLift = 0
): SongSection {
  const cloned = cloneTracks(baseTracks);
  const melody = cloned.find((t) => t.role === 'melody');
  if (melody) {
    melody.notes = melody.notes.map((n) => ({
      ...n,
      id: `${id}-${n.id}`,
      semitoneOffset: Math.min(23, n.semitoneOffset + octaveLift),
      gamaka: n.gamaka === 'none' && octaveLift > 0 ? 'sphurita' : n.gamaka,
      velocity: Math.min(1, n.velocity + (octaveLift > 0 ? 0.04 : 0)),
    }));
  }
  return {
    id,
    name,
    roleLabel,
    repeats: 1,
    tracks: cloned,
  };
}

